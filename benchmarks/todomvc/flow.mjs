import { expect } from '@playwright/test';

/** One behavioral contract for every implementation and the Pages example. */
export async function todoFlow(page, url, { phase = async () => {}, screenshot = async () => {}, storageKey = 'todos-isle' } = {}) {
  const titles = () => page.locator('.todo-title');
  const rows = () => page.locator('.todo-list li');
  const input = page.getByRole('textbox', { name: 'New todo', exact: true });
  const add = async title => { await input.fill(title); await input.press('Enter'); };
  await page.goto(url, { waitUntil: 'load' });
  await expect(page.locator('h1')).toHaveText('todos');
  await expect(input).toBeFocused();
  await expect(input).toHaveAttribute('placeholder', 'What needs to be done?');
  await expect(page.locator('.main')).toBeHidden();
  await expect(page.locator('.footer')).toBeHidden();
  await phase('initial');
  await add('  Write tests  ');
  await expect(titles()).toHaveText(['Write tests']);
  await expect(input).toHaveValue('');
  await phase('first-add');
  await add('Ship demo'); await expect(titles()).toHaveCount(2);
  await add('Review size'); await expect(titles()).toHaveCount(3);
  await add('   '); await expect(titles()).toHaveCount(3);
  await expect(page.locator('.todo-count')).toHaveText('3 items left');
  await page.evaluate(() => { window.__todoFirst = document.querySelector('.todo-list li'); });
  await rows().nth(0).locator('.toggle').check();
  await expect(rows().nth(0)).toHaveClass('completed');
  await expect(page.locator('.todo-count')).toHaveText('2 items left');
  expect(await page.evaluate(() => window.__todoFirst === document.querySelector('.todo-list li'))).toBe(true);
  await screenshot('populated');
  await page.getByRole('link', { name: 'Active', exact: true }).click();
  await expect(titles()).toHaveText(['Ship demo', 'Review size']);
  // The clicked row disappears; .check() would re-resolve and toggle the following row.
  await rows().nth(0).locator('.toggle').click();
  await expect(titles()).toHaveText(['Review size']);
  await page.getByRole('link', { name: 'Completed', exact: true }).click();
  await expect(titles()).toHaveText(['Write tests', 'Ship demo']);
  await rows().nth(1).locator('.toggle').click();
  await expect(titles()).toHaveText(['Write tests']);
  await page.getByRole('link', { name: 'All', exact: true }).click();
  await expect(titles()).toHaveCount(3);
  await titles().nth(1).dblclick();
  const edit = page.locator('.editing .edit');
  await expect(edit).toBeFocused();
  await edit.fill('  Ship accessible demo  ');
  await screenshot('editing');
  await edit.press('Enter');
  await expect(titles()).toHaveText(['Write tests', 'Ship accessible demo', 'Review size']);
  await titles().nth(1).press('Enter'); await expect(edit).toBeFocused();
  await edit.fill('Discard me'); await edit.press('Escape');
  await expect(titles().nth(1)).toHaveText('Ship accessible demo');
  await titles().nth(1).click(); await expect(edit).toBeFocused();
  await edit.fill(' Saved on blur '); await input.click();
  await expect(titles().nth(1)).toHaveText('Saved on blur');
  await titles().nth(2).click(); await expect(edit).toBeFocused();
  await edit.fill('  '); await edit.press('Enter');
  await expect(titles()).toHaveCount(2);
  await phase('crud');
  await page.getByRole('link', { name: 'Active', exact: true }).click();
  await expect(titles()).toHaveText(['Saved on blur']);
  await expect.poll(() => page.evaluate(key => localStorage.getItem(key), storageKey)).toContain('Saved on blur');
  await page.reload();
  await expect(titles()).toHaveText(['Saved on blur']);
  await expect(page.locator('.filters .selected')).toHaveText('Active');
  await page.getByRole('link', { name: 'All', exact: true }).click();
  await expect(titles()).toHaveText(['Write tests', 'Saved on blur']);
  await rows().nth(1).getByRole('button', { name: 'Delete todo' }).click();
  await expect(titles()).toHaveText(['Write tests']);
  await add('Last active'); await expect(titles()).toHaveCount(2);
  await page.locator('.toggle-all').check();
  await expect(page.locator('.todo-count')).toHaveText('0 items left');
  await page.locator('.toggle-all').uncheck();
  await expect(page.locator('.todo-count')).toHaveText('2 items left');
  await page.locator('.toggle-all').check();
  await page.getByRole('button', { name: 'Clear completed' }).click();
  await expect(titles()).toHaveCount(0);
  await expect(page.locator('.main')).toBeHidden();
  await expect(page.locator('.footer')).toBeHidden();
  await expect(page.locator('.toggle-all')).not.toBeChecked();
  await expect.poll(() => page.evaluate(key => localStorage.getItem(key), storageKey)).toBe('[]');
  await phase('complete');
}
